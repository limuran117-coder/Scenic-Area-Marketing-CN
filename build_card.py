def fmt_arrow(t):
    s = t.strip()
    if s.startswith("+"):
        return "↑" + s[1:]
    if s.startswith("-"):
        return "↓" + s[1:]
    return "➖" + s

def fmt_anomaly(t, is_movie_town=False):
    s = fmt_arrow(t)
    if is_movie_town:
        return s
    # 异动标准：绝对值>=20% 或 特殊标记
    pct = t.replace("+", "").replace("-", "").replace("%", "")
    try:
        v = abs(float(pct))
        if v >= 100 or "353" in t or "319" in t:
            return "🔺 " + s
    except: pass
    return s

